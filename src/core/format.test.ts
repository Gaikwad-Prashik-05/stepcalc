import { describe, expect, it } from 'vitest';
import { formatNumber } from './format';

describe('formatNumber', () => {
  it.each([
    ['0', '0'],
    ['-0', '0'],
    ['2', '2'],
    ['2.50', '2.5'],
    ['0.3', '0.3'],
    ['-2', '-2'],
    ['11720', '11,720'],
    ['11711', '11,711'],
    ['1234567.5', '1,234,567.5'],
    ['-1234567', '-1,234,567'],
    ['99999999999999', '99,999,999,999,999'],
    // 12 significant digits, half-up
    ['0.91666666666666666666', '0.916666666667'],
    ['91.666666666666666', '91.6666666667'],
    ['3.33333333333333333', '3.33333333333'],
    ['0.1234567890125', '0.123456789013'],
    ['123456789012.5', '123,456,789,013'],
    // exponent outside [1e-9, 1e15)
    ['1e60', '1e+60'],
    ['1000000000000000', '1e+15'],
    ['999999999999999', '999,999,999,999,999'],
    ['999999999999999.9', '1e+15'],
    ['123456789012345.6', '123,456,789,012,346'],
    ['12345678901234.5678', '12,345,678,901,235'],
    ['0.000000000123', '1.23e-10'],
    ['0.000000001', '0.000000001'],
    ['-0.00000000025', '-2.5e-10'],
  ])('%s -> %s', (exact, display) => {
    expect(formatNumber(exact)).toBe(display);
  });
});
