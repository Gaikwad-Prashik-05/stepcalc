import { describe, expect, it } from 'vitest';
import { formatEng, formatNumber, toFraction } from './format';

describe('formatNumber', () => {
  it.each([
    ['0', '0'],
    ['-0', '0'],
    ['2', '2'],
    ['2.50', '2.5'],
    ['0.3', '0.3'],
    ['-2', '-2'],
    ['11720', '11,720'],
    ['11711', '11,711'],
    ['1234567.5', '1,234,567.5'],
    ['-1234567', '-1,234,567'],
    ['99999999999999', '99,999,999,999,999'],
    // 12 significant digits, half-up
    ['0.91666666666666666666', '0.916666666667'],
    ['91.666666666666666', '91.6666666667'],
    ['3.33333333333333333', '3.33333333333'],
    ['0.1234567890125', '0.123456789013'],
    ['123456789012.5', '123,456,789,013'],
    // exponent outside [1e-9, 1e15)
    ['1e60', '1e+60'],
    ['1000000000000000', '1e+15'],
    ['999999999999999', '999,999,999,999,999'],
    ['999999999999999.9', '1e+15'],
    ['123456789012345.6', '123,456,789,012,346'],
    ['12345678901234.5678', '12,345,678,901,235'],
    ['0.000000000123', '1.23e-10'],
    // exponent form keeps 12 significant digits too
    ['100000000000000000001', '1e+20'],
    ['123456789012345678', '1.23456789012e+17'],
    ['0.000000001', '0.000000001'],
    ['-0.00000000025', '-2.5e-10'],
  ])('%s -> %s', (exact, display) => {
    expect(formatNumber(exact)).toBe(display);
  });
});

it('formats a huge exponent without expanding its digits', () => {
  expect(formatNumber('1e+999999999')).toBe('1e+999999999');
});

describe('formatEng: exponent a multiple of 3', () => {
  it.each([
    ['1500', '1.5×10³'], ['42', '42'], ['0.5', '500×10⁻³'], ['0.000123', '123×10⁻⁶'],
    ['-25000', '-25×10³'], ['1e21', '1×10²¹'], ['0', '0'], ['999.9999999999999', '1×10³'],
    ['123456789012345', '123.456789012×10¹²'],
  ])('%s → %s', (exact, expected) => {
    expect(formatEng(exact)).toBe(expected);
  });
});

describe('toFraction', () => {
  const third = '0.3333333333333333333333333333333333333333333333333333333333333333';
  it.each([
    [third, '1/3'], ['0.5', '1/2'], ['-0.75', '-3/4'], ['1.6666666666666666666666666666666666666666666666666666666666666667', '5/3'],
    ['0.0001', '1/10,000'], ['2.5', '5/2'],
  ])('%s → %s', (exact, expected) => {
    expect(toFraction(exact)).toBe(expected);
  });

  it.each([['3'], ['0'], ['0.00001'], ['3.14159265358979323846264338327950288419716939937510582097494459']])('no fraction for %s', (exact) => {
    expect(toFraction(exact)).toBeNull();
  });
});
