import type { Point, Stroke } from './recognizer';

// Built-in symbol shapes, drawn in a box about 0.6 wide and 1 tall (y grows downwards).
// They only seed the recogniser: the user's own samples (Teach, tap-to-fix) do the real work.

const p = (x: number, y: number): Point => ({ x, y });
const poly = (...xy: number[]): Stroke => Array.from({ length: xy.length / 2 }, (_, i) => p(xy[2 * i], xy[2 * i + 1]));
/** Elliptical arc from angle a0 to a1 in degrees (0 = right, 90 = down). */
function arc(cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, steps = 24): Stroke {
  return Array.from({ length: steps + 1 }, (_, i) => {
    const a = ((a0 + ((a1 - a0) * i) / steps) * Math.PI) / 180;
    return p(cx + rx * Math.cos(a), cy + ry * Math.sin(a));
  });
}
const join = (...parts: Stroke[]): Stroke => parts.flat();

